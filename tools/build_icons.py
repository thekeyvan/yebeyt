"""Converts the prototype's inline SVG icons (path / circle / rect) into one path string each,
and writes Yebeyt/UI/IconData.swift. Usage: python3 build_icons.py design/prototype.html Yebeyt/UI/IconData.swift"""
import re, sys
src = open(sys.argv[1]).read()

def block(name):
    m = re.search(r'const ' + name + r' = \{(.*?)\n\};', src, re.S)
    return dict(re.findall(r"(\w+):'([^']*)'", m.group(1)))

def num(a, k, d=0.0):
    m = re.search(r'\b' + k + r'="([-\d.]+)"', a)
    return float(m.group(1)) if m else d

def f(x): return ('%.3f' % x).rstrip('0').rstrip('.')

def to_d(svg):
    out = []
    for tag, attrs in re.findall(r'<(path|circle|rect)\b([^>]*)/?>', svg):
        if tag == 'path':
            d = re.search(r'd="([^"]*)"', attrs).group(1).strip()
            # A path's first moveto is absolute even when written lowercase; keep it so once joined.
            m = re.match(r'm\s*(-?\d*\.?\d+)[ ,]*(-?\d*\.?\d+)(.*)', d, re.S)
            if m:
                rest = m.group(3).strip()
                d = 'M' + m.group(1) + ' ' + m.group(2) + ((' l' + rest) if rest and not rest[0].isalpha() else (' ' + rest if rest else ''))
            out.append(d)
        elif tag == 'circle':
            cx, cy, r = num(attrs, 'cx'), num(attrs, 'cy'), num(attrs, 'r')
            out.append(f"M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2*r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2*r)} 0z")
        else:
            x, y, w, h, rx = num(attrs, 'x'), num(attrs, 'y'), num(attrs, 'width'), num(attrs, 'height'), num(attrs, 'rx')
            if rx == 0:
                out.append(f"M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}z")
            else:
                out.append(f"M{f(x+rx)} {f(y)}h{f(w-2*rx)}a{f(rx)} {f(rx)} 0 0 1 {f(rx)} {f(rx)}v{f(h-2*rx)}a{f(rx)} {f(rx)} 0 0 1 {f(-rx)} {f(rx)}h{f(-(w-2*rx))}a{f(rx)} {f(rx)} 0 0 1 {f(-rx)} {f(-rx)}v{f(-(h-2*rx))}a{f(rx)} {f(rx)} 0 0 1 {f(rx)} {f(-rx)}z")
    return ' '.join(out)

icons = {k: to_d(v) for k, v in block('I').items()}
icons['play'] = 'M7 4.5v15l13-7.5z'
icons['pause'] = to_d('<rect x="6" y="4" width="4" height="16" rx="1"/><rect x="14" y="4" width="4" height="16" rx="1"/>')
icons['ai'] = 'M11 3l1.9 5.6L18.5 10.5l-5.6 1.9L11 18l-1.9-5.6L3.5 10.5l5.6-1.9z M18.5 15l.7 1.9 1.9.7-1.9.7-.7 1.9-.7-1.9-1.9-.7 1.9-.7z'
emb = {k: to_d(v) for k, v in block('EMB').items()}
sh = re.search(r"const SHAMSE = '(.*?)';", src).group(1)
mot = {k: to_d(v) for k, v in block('MOTIF').items()}

def dict_swift(name, d):
    rows = ',\n'.join(f'        "{k}": "{v}"' for k, v in sorted(d.items()))
    return f'    static let {name}: [String: String] = [\n{rows},\n    ]\n'

with open(sys.argv[2], 'w') as o:
    o.write('// Generated by tools/build_icons.py from the prototype\'s hand-drawn icons. Do not edit by hand.\n\n')
    o.write('enum IconData {\n    /// 24×24 line icons (stroke 1.8)\n')
    o.write(dict_swift('icons', icons))
    o.write('    /// 48×48 poet emblems\n' + dict_swift('emblems', emb))
    o.write('    /// 48×48 scene motifs\n' + dict_swift('motifs', mot))
    o.write('    /// 100×100 shamse ornament for book covers\n    static let shamse = "' + to_d(sh) + '"\n')
    o.write('}\n')
print(len(icons), 'icons', len(emb), 'emblems', len(mot), 'motifs')
