"""Write the platform token files from packages/tokens/tokens.json (Swift for the iOS app, CSS for the website, a Tailwind theme for the web app).
Run `python3 tools/make_tokens.py` from anywhere; `--check` exits 1 and names each file that is out of date."""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "packages", "tokens", "tokens.json")
SWIFT = os.path.join(ROOT, "apps", "ios", "Yebeyt", "Design", "Tokens.swift")
CSS = os.path.join(ROOT, "apps", "web", "app", "tokens.css")
THEME = os.path.join(ROOT, "apps", "webapp", "app", "theme.css")

def num(v):
    return repr(float(v)) if isinstance(v, float) else str(v)

def swift(t):
    L = ["// Generated by tools/make_tokens.py from packages/tokens/tokens.json. Do not edit.", "",
         "import SwiftUI", "", "struct FontToken: Sendable {", "    let file: String", "    let postScript: String", "    /// The boards scale Parastoo to 84% (CSS size-adjust); multiply a board size by this.", "    let sizeAdjust: CGFloat", "}", "",
         "struct ShadowToken: Sendable {", "    let y: CGFloat", "    let blur: CGFloat", "    let opacity: Double", "}", "",
         "extension Color {", "    init(hex: UInt32) {",
         "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)",
         "    }", "}", "", "enum Tokens {", "    enum Colors {"]
    for k, v in t["colors"].items():
        L.append(f"        static let {k} = Color(hex: 0x{v.lstrip('#').upper()})")
    L += ["    }", "", "    enum Fonts {"]
    for k, v in t["fonts"].items():
        L.append(f'        static let {k} = FontToken(file: "{v["file"]}", postScript: "{v["postScript"]}", sizeAdjust: {num(v["sizeAdjust"])})')
    L += ["        static let all = [" + ", ".join(t["fonts"]) + "]", "    }", "", "    /// The fonts of the reader's text sheet besides Parastoo (which is `Fonts.poem` and `Fonts.poemRegular`).", "    enum ReaderFonts {"]
    for k, v in t["readerFonts"].items():
        L.append(f'        static let {k} = FontToken(file: "{v["file"]}", postScript: "{v["postScript"]}", sizeAdjust: {num(v["sizeAdjust"])})')
    L += ["        static let all = [" + ", ".join(t["readerFonts"]) + "]", "    }", "", "    enum Sticker {"]
    for group in ("borderWidth", "radius", "tilt", "scale"):
        L.append(f"        enum {group[0].upper()}{group[1:]} {{")
        L += [f"            static let {k}: CGFloat = {num(v)}" for k, v in t["sticker"][group].items()]
        L.append("        }")
    L.append("        enum Shadow {")
    for k, v in t["sticker"]["shadow"].items():
        L.append(f"            static let {k} = ShadowToken(y: {num(v['y'])}, blur: {num(v['blur'])}, opacity: {num(v['opacity'])})")
    L += ["        }", "        enum Dots {"]
    L += [f"            static let {k}: CGFloat = {num(v)}" for k, v in t["sticker"]["dots"].items()]
    L += ["        }", "    }", "}", ""]
    return "\n".join(L)

def kebab(name):
    return "".join("-" + c.lower() if c.isupper() else c for c in name)

def rgba(hex_colour, opacity):
    h = hex_colour.lstrip("#")
    return f"rgba({int(h[0:2], 16)},{int(h[2:4], 16)},{int(h[4:6], 16)},{num(opacity)})"

def css(t):
    """Custom properties for colours, sizes and shadows, and the @font-face rules of the main fonts.
    The font files are copied from assets/fonts into public/fonts by packages/tokens/copy-fonts.mjs."""
    L = ["/* Generated by tools/make_tokens.py from packages/tokens/tokens.json. Do not edit. */", ""]
    for k, v in t["fonts"].items():
        # A weight range, so the browser never fakes a bold over a font that has one weight (Lalezar, Parastoo).
        L += ["@font-face {", f'  font-family: "yebeyt-{kebab(k)}";', f'  src: url("/fonts/{v["file"]}") format("truetype");',
              "  font-weight: 100 900;", "  font-display: swap;", f"  size-adjust: {num(round(v['sizeAdjust'] * 100, 2)).rstrip('0').rstrip('.')}%;", "}", ""]
    ink = t["colors"]["ink"]
    L.append(":root {")
    L += [f"  --color-{kebab(k)}: {v};" for k, v in t["colors"].items()]
    L += [f'  --font-{kebab(k)}: "yebeyt-{kebab(k)}";' for k in t["fonts"]]
    for group in ("borderWidth", "radius"):
        L += [f"  --{kebab(group)}-{kebab(k)}: {v}px;" for k, v in t["sticker"][group].items()]
    for k, v in t["sticker"]["shadow"].items():
        L.append(f"  --shadow-{kebab(k)}: 0 {v['y']}px {v['blur']}px {rgba(ink, v['opacity'])};")
    L += [f"  --tilt-{kebab(k)}: {v}deg;" for k, v in t["sticker"]["tilt"].items()]
    L.append(f"  --scale-held: {t['sticker']['scale']['held']};")
    L += [f"  --dots-grid: {t['sticker']['dots']['grid']}px;", f"  --dots-radius: {t['sticker']['dots']['radius']}px;", "}", ""]
    return "\n".join(L)

def theme(t):
    """The web app's Tailwind v4 theme: the @font-face rules (the main and the reader fonts; the files are copied by
    packages/tokens/copy-fonts.mjs --reader), and an @theme with the colours, fonts, radii and shadows (`bg-lapis`,
    `font-title`, `rounded-card`, `shadow-card`), plus the sticker border widths as `border-badge` … `border-button`."""
    L = ["/* Generated by tools/make_tokens.py from packages/tokens/tokens.json. Do not edit. */", ""]
    family = {}  # font file -> the family its @font-face names (Vazirmatn is both the UI font and a reader font)
    fonts = {**t["fonts"], **t["readerFonts"]}
    for k, v in fonts.items():
        if v["file"] in family:
            continue
        family[v["file"]] = f"yebeyt-{kebab(k)}"
        L += ["@font-face {", f'  font-family: "{family[v["file"]]}";', f'  src: url("/fonts/{v["file"]}") format("truetype");',
              "  font-weight: 100 900;", "  font-display: swap;", f"  size-adjust: {num(round(v['sizeAdjust'] * 100, 2)).rstrip('0').rstrip('.')}%;", "}", ""]
    ink = t["colors"]["ink"]
    L += ["@theme static {", "  --color-*: initial;"]
    L += [f"  --color-{kebab(k)}: {v};" for k, v in t["colors"].items()]
    L += [f'  --font-{kebab(k)}: "{family[v["file"]]}", system-ui, sans-serif;' for k, v in fonts.items()]
    L += [f"  --radius-{kebab(k)}: {v}px;" for k, v in t["sticker"]["radius"].items()]
    L += [f"  --shadow-{kebab(k)}: 0 {v['y']}px {v['blur']}px {rgba(ink, v['opacity'])};" for k, v in t["sticker"]["shadow"].items()]
    L += [f"  --tilt-{kebab(k)}: {v}deg;" for k, v in t["sticker"]["tilt"].items()]
    L += [f"  --scale-held: {t['sticker']['scale']['held']};", f"  --dots-grid: {t['sticker']['dots']['grid']}px;", f"  --dots-radius: {t['sticker']['dots']['radius']}px;", "}", ""]
    for k, v in t["sticker"]["borderWidth"].items():
        L += [f"@utility border-{kebab(k)} {{", f"  border-width: {v}px;", "}", ""]
    return "\n".join(L)

def main():
    tokens = json.load(open(SRC, encoding="utf-8"))
    outputs = {SWIFT: swift(tokens), CSS: css(tokens), THEME: theme(tokens)}
    if "--check" in sys.argv:
        stale = [p for p, out in outputs.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != out]
        for p in stale:
            print(f"out of date: {os.path.relpath(p, ROOT)} (run python3 tools/make_tokens.py)")
        if stale:
            sys.exit(1)
        print("tokens up to date")
        return
    for p, out in outputs.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", encoding="utf-8").write(out)
        print("wrote", os.path.relpath(p, ROOT))

main()
