/** The names of the schemas a piece of the contract points at, and those they point at in turn. */
function reached(document, node, found = new Set()) {
  const text = JSON.stringify(node);
  for (const [, name] of text.matchAll(/#\/components\/schemas\/([A-Za-z0-9_]+)/g)) {
    if (!found.has(name)) {
      found.add(name);
      reached(document, document.components.schemas[name], found);
    }
  }
  return found;
}

export async function render() {
  const document = JSON.parse(readFileSync(contract, "utf8"));
  const paths = Object.fromEntries(usedPaths.map((path) => [path, document.paths[path]]));
  const names = reached(document, paths);
  const schemas = Object.fromEntries([...names].sort().map((name) => [name, document.components.schemas[name]]));
  const small = { openapi: document.openapi, info: document.info, paths, components: { schemas, securitySchemes: document.components.securitySchemes } };
  const types = astToString(await openapiTS(small));
  return `// Generated by scripts/api-types.mjs from packages/api/openapi.json (pnpm --filter @yebeyt/webapp api:types). Do not edit.\n${types}`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const text = await render();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== text) {
      console.error("lib/api/schema.d.ts is out of date: run `pnpm --filter @yebeyt/webapp api:types` and commit it.");
      process.exit(1);
    }
  } else {
    writeFileSync(target, text);
  }
}
